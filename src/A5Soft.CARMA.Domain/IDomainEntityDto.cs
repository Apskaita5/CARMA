namespace A5Soft.CARMA.Domain
{
    /// <summary>
    /// A contract of the DTO of a domain entity of type <typeparamref name="T"/>: a domain
    /// object that is one of many, identified by a <see cref="DomainEntityIdentity{T}"/>.
    /// </summary>
    /// <typeparam name="T">a type of the domain entity the DTO carries data for</typeparam>
    /// <remarks>Not covariant: <see cref="DomainEntityIdentity{T}"/> is a class, so
    /// <see cref="Id"/> is not variance safe.</remarks>
    public interface IDomainEntityDto<T> : IDomainObjectDto<T>
        where T : class
    {
        /// <summary>
        /// Gets an identity of the domain entity.
        /// </summary>
        /// <remarks>Could be null for a domain entity that has not been persisted yet;
        /// however if the id is generated by an app service (not a repository),
        /// it could be non null for a new entity.</remarks>
        DomainEntityIdentity<T> Id { get; }

        /// <summary>
        /// Gets a value indicating whether the domain entity has not been persisted yet.
        /// </summary>
        bool IsNew { get; }
    }
}
